/**
 * Generates/updates only .ai/FILE_STRUCTURE.md by scanning the project tree.
 * Safe to run repeatedly. Uses Node.js built-ins only (CommonJS).
 * Works on Windows and Linux.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, '.ai');
const OUT_FILE = path.join(OUT_DIR, 'FILE_STRUCTURE.md');

const IGNORE_DIRS = new Set([
  'node_modules',
  '.git',
  'dist',
  'build',
  'coverage',
  '.cache',
  '.vite',
  '.turbo',
  '.next',
  '.nuxt',
  '.output',
  '.vercel',
  '.idea',
  '.vscode',
  '__pycache__',
  '.pytest_cache',
  'uploads',
  'lms_mysql_data',
]);

const IGNORE_FILES = new Set([
  '.DS_Store',
  'Thumbs.db',
  'npm-debug.log',
  'yarn-error.log',
  'package-lock.json',
]);

function shouldIgnoreDir(name) {
  if (IGNORE_DIRS.has(name)) return true;
  if (name.startsWith('.') && name !== '.ai' && name !== '.github') return true;
  return false;
}

function shouldIgnoreFile(name) {
  if (IGNORE_FILES.has(name)) return true;
  if (name.endsWith('.log')) return true;
  if (name === '.env' || name.startsWith('.env.') && !name.endsWith('.example')) {
    // Keep *.example; skip real env files
    if (!name.endsWith('.example')) return true;
  }
  return false;
}

function listEntries(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((e) => {
      if (e.isDirectory()) return !shouldIgnoreDir(e.name);
      return !shouldIgnoreFile(e.name);
    })
    .sort((a, b) => {
      if (a.isDirectory() && !b.isDirectory()) return -1;
      if (!a.isDirectory() && b.isDirectory()) return 1;
      return a.name.localeCompare(b.name);
    });
}

function walk(dir, prefix, lines, depth, maxDepth) {
  if (depth > maxDepth) return;
  const entries = listEntries(dir);
  entries.forEach((entry, index) => {
    const isLast = index === entries.length - 1;
    // ASCII-only connectors for reliable cross-platform file encoding
    const branch = isLast ? '`-- ' : '|-- ';
    const nextPrefix = prefix + (isLast ? '    ' : '|   ');
    if (entry.isDirectory()) {
      lines.push(`${prefix}${branch}${entry.name}/`);
      walk(path.join(dir, entry.name), nextPrefix, lines, depth + 1, maxDepth);
    } else {
      lines.push(`${prefix}${branch}${entry.name}`);
    }
  });
}

function generate() {
  const lines = [];
  const rootName = path.basename(ROOT);
  lines.push(`# File Structure`);
  lines.push('');
  lines.push('Auto-generated by `scripts/generate-ai-context.cjs`. Do not edit manually; re-run `npm run ai:context`.');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push('');
  lines.push('Ignored during scan: `node_modules`, `.git`, `dist`, `build`, `coverage`, caches, `uploads`, lockfiles, and secret `.env` files (`.env*.example` kept).');
  lines.push('');
  lines.push('```');
  lines.push(`${rootName}/`);
  walk(ROOT, '', lines, 0, 12);
  lines.push('```');
  lines.push('');

  if (!fs.existsSync(OUT_DIR)) {
    fs.mkdirSync(OUT_DIR, { recursive: true });
  }
  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}`);
}

generate();
